def context():
    d = DFD(200, 112)
    p = d.process(100, 57, "0", "ИС учёта заказов\nи клиентов автосервиса", w=48, h=24)
    cl = d.entity(24, 98, CL)
    ma = d.entity(24, 16, MA)
    me = d.entity(100, 104, ME)
    ru = d.entity(100, 9, RU)
    sms = d.entity(176, 98, SMS)
    kkt = d.entity(176, 16, KKT)
    tm = d.entity(24, 57, "Таймер\n(расписание)")
    d.link(tm, p, "Сигнал расписания", side=1)

    for a, b, lab_ab, lab_ba in [
        (cl, p, "Онлайн-заявка,\nрешение по доп. работам", "Электронная\nквитанция и чек"),
        (ma, p, "Данные клиента и автомобиля,\nзаявка, выбор исполнителя,\nрешение клиента, оплата",
         "Стоимость, акт приёма,\nпредупреждения, уведомления,\nквитанция"),
        (me, p, "Статус работ,\nдоп. работы,\nзапчасти", "Заказ-наряд"),
        (ru, p, "Прейскурант,\nпараметры\nотчётов", "Отчёты"),
        (p, sms, "Текст SMS,\nномер телефона", "Статус доставки"),
        (p, kkt, "Данные\nкассового чека", "Фискальный\nпризнак чека"),
    ]:
        d.link(a, b, lab_ab, off=2.5)
        d.link(b, a, lab_ba, off=2.5)
    d.save("dfd_context.png")


