def updated_spec():
    rows = []
    for r in BASE:
        if isinstance(r, str):
            rows.append(r)
            continue
        rid = r[0]
        if rid in CHANGES:
            kind, text, pr, te, cx, _ = CHANGES[rid]
            rows.append([[rid, f"({kind})"], f"**{text}**", pr, te, cx])
        else:
            rows.append(r)
    assert all(isinstance(r, str) or r[1] for r in rows), "пустое требование"
    return rows


