# ---------------------------------------------------------------- helpers
def fmt_run(run, size=14, bold=False, italic=False, font=FONT):
    run.font.name = font
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.italic = italic
    rpr = run._r.get_or_add_rPr()
    rfonts = rpr.find(qn("w:rFonts"))
    if rfonts is None:
        rfonts = OxmlElement("w:rFonts")
        rpr.insert(0, rfonts)
    for attr in ("w:ascii", "w:hAnsi", "w:cs", "w:eastAsia"):
        rfonts.set(qn(attr), font)


def fmt_par(p, align=J, indent=True, spacing=1.5, before=0, after=0, keep_next=False):
    pf = p.paragraph_format
    pf.alignment = align
    pf.first_line_indent = Cm(1.25) if indent else Cm(0)
    pf.line_spacing = spacing
    pf.space_before = Pt(before)
    pf.space_after = Pt(after)
    pf.keep_with_next = keep_next


def para(text="", bold=False, italic=False, align=J, indent=True, size=14, **kw):
    p = doc.add_paragraph()
    fmt_par(p, align=align, indent=indent, **kw)
    if text:
        add_rich(p, text, size=size, bold=bold, italic=italic)
    return p


def add_rich(p, text, size=14, bold=False, italic=False):
    """Поддержка **жирного** фрагмента внутри строки."""
    parts = text.split("**")
    for i, part in enumerate(parts):
        if part:
            fmt_run(p.add_run(part), size=size, bold=bold or (i % 2 == 1), italic=italic)


def heading(text, level=1):
    p = doc.add_paragraph()
    fmt_par(p, align=LFT if level > 1 else C, indent=level > 1, before=12 if level == 1 else 6,
            after=6, keep_next=True)
    fmt_run(p.add_run(text), size=14, bold=True)
    ppr = p._p.get_or_add_pPr()
    lvl = OxmlElement("w:outlineLvl")
    lvl.set(qn("w:val"), str(level - 1))
    ppr.append(lvl)
    return p


def bullets(items, marker="–"):
    for it in items:
        p = doc.add_paragraph()
        fmt_par(p, indent=True)
        add_rich(p, f"{marker} {it}")


def caption_table(text):
    p = para(text, align=LFT, indent=False, keep_next=True, before=6)
    return p


def caption_figure(text):
    return para(text, align=C, indent=False, after=6)


def page_break():
    p = doc.add_paragraph()
    p.add_run().add_break(WD_BREAK.PAGE)


def set_cell_borders(table):
    tbl = table._tbl
    tblPr = tbl.tblPr
    borders = OxmlElement("w:tblBorders")
    for edge in ("top", "left", "bottom", "right", "insideH", "insideV"):
        el = OxmlElement(f"w:{edge}")
        el.set(qn("w:val"), "single")
        el.set(qn("w:sz"), "4")
        el.set(qn("w:space"), "0")
        el.set(qn("w:color"), "000000")
        borders.append(el)
    tblPr.append(borders)


def shade(cell, color="E7E6E6"):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), color)
    tcPr.append(shd)


def repeat_header(row):
    trPr = row._tr.get_or_add_trPr()
    el = OxmlElement("w:tblHeader")
    el.set(qn("w:val"), "true")
    trPr.append(el)


def cell_write(cell, text, size=12, bold=False, align=LFT):
    """text может быть строкой или списком абзацев."""
    paras = text if isinstance(text, list) else [text]
    cell.paragraphs[0].text = ""
    for i, t in enumerate(paras):
        p = cell.paragraphs[0] if i == 0 else cell.add_paragraph()
        fmt_par(p, align=align, indent=False, spacing=1.0)
        add_rich(p, t, size=size, bold=bold)
    cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.TOP


def table(header, rows, widths, center_cols=(), size=12):
    t = doc.add_table(rows=1, cols=len(header))
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    set_cell_borders(t)
    for i, h in enumerate(header):
        c = t.rows[0].cells[i]
        cell_write(c, h, size=size, bold=True, align=C)
        shade(c)
    repeat_header(t.rows[0])
    for c in t.rows[0].cells:  # шапка не отрывается от первой строки
        for cp in c.paragraphs:
            cp.paragraph_format.keep_with_next = True
    for r in rows:
        if isinstance(r, str):  # строка-раздел на всю ширину
            cells = t.add_row().cells
            m = cells[0].merge(cells[-1])
            cell_write(m, r, size=size, bold=True)
            shade(m, "F2F2F2")
            m.paragraphs[0].paragraph_format.keep_with_next = True
            continue
        cells = t.add_row().cells
        for i, v in enumerate(r):
            cell_write(cells[i], v, size=size, align=C if i in center_cols else LFT)
    for row in t.rows:
        cant = OxmlElement("w:cantSplit")  # строка не разрывается между страницами
        row._tr.get_or_add_trPr().append(cant)
        for i, w in enumerate(widths):
            row.cells[i].width = Cm(w)
    para("", spacing=1.0)
    return t


def new_section(landscape):
    sec = doc.add_section(WD_SECTION.NEW_PAGE)
    if landscape:
        sec.orientation = WD_ORIENT.LANDSCAPE
        sec.page_width, sec.page_height = Cm(29.7), Cm(21.0)
        sec.left_margin = sec.right_margin = Cm(2.0)
        sec.top_margin, sec.bottom_margin = Cm(1.5), Cm(1.5)
    else:
        sec.orientation = WD_ORIENT.PORTRAIT
        sec.page_width, sec.page_height = Cm(21.0), Cm(29.7)
        sec.left_margin, sec.right_margin = Cm(3.0), Cm(1.5)
        sec.top_margin, sec.bottom_margin = Cm(2.0), Cm(2.0)
    return sec


def figure(path, width_cm, caption):
    p = doc.add_paragraph()
    fmt_par(p, align=C, indent=False, spacing=1.0, keep_next=True)
    p.add_run().add_picture(path, width=Cm(width_cm))
    caption_figure(caption)


def add_page_number_footer(section):
    section.different_first_page_header_footer = True
    p = section.footer.paragraphs[0]
    p.alignment = C
    run = p.add_run()
    for tag, txt in (("begin", None), (None, "PAGE"), ("end", None)):
        if tag:
            el = OxmlElement("w:fldChar")
            el.set(qn("w:fldCharType"), tag)
        else:
            el = OxmlElement("w:instrText")
            el.set(qn("xml:space"), "preserve")
            el.text = txt
        run._r.append(el)
    fmt_run(run, size=12)


